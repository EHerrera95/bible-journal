class Command(BaseCommand):
    help = "Seed the M'Cheyne/Carson Classic Two-Year Bible Reading Plan (730 days)."

    def handle(self, *args, **kwargs):
        self.stdout.write("Seeding M'Cheyne Two-Year Bible Reading Plan…")

        plan, created = ReadingPlan.objects.get_or_create(
            name="M'Cheyne Classic Two-Year Plan",
            defaults={
                "description": (
                    "The classic plan adapted by D.A. Carson from Robert Murray M'Cheyne's "
                    "original design. Read through the entire Bible in two years — "
                    "each day pairs an Old Testament passage with a New Testament, "
                    "Psalms, or Gospels reading. 730 days total. Start any day of the year."
                )
            },
        )
        action = "Created" if created else "Found existing"
        self.stdout.write(f"  {action} plan: {plan.name}")

        # Year 1: days 1–365
        y1_created = 0
        for day_num, ot, nt in YEAR1:
            passages = f"{ot} | {nt}"
            kv = key_verse_for(ot, nt)
            _, c = PlanDay.objects.get_or_create(
                plan=plan,
                day_number=day_num,
                defaults={"passages": passages, "key_verse_ref": kv},
            )
            if c:
                y1_created += 1
        self.stdout.write(f"  Year 1: {y1_created} new days created (365 total)")

        # Year 2: days 366–730
        y2_created = 0
        for rel_day, ot, nt in YEAR2:
            day_num = 365 + rel_day
            passages = f"{ot} | {nt}"
            kv = key_verse_for(ot, nt)
            _, c = PlanDay.objects.get_or_create(
                plan=plan,
                day_number=day_num,
                defaults={"passages": passages, "key_verse_ref": kv},
            )
            if c:
                y2_created += 1
        self.stdout.write(f"  Year 2: {y2_created} new days created (days 366–730)")

        total = PlanDay.objects.filter(plan=plan).count()
        self.stdout.write(self.style.SUCCESS(
            f"\n✓ Done. Plan '{plan.name}' now has {total} days.\n"
            f"  Users can select it at /plans/"
        ))
