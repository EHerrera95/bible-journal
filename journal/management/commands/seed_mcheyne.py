def key_verse_for(ot_passage, nt_passage):
    """Pick the best key verse for a day's readings."""
    for p in (ot_passage, nt_passage):
        if p in KEY_VERSES:
            return KEY_VERSES[p]
    # Default: first reference + :1
    first = ot_passage.split(";")[0].strip().split(":")[0].strip()
    return f"{first}:1"


